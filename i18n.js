let currentLang = 'de';

function getInitialLang() {
  const saved = localStorage.getItem('disrupt_lang');
  if (saved === 'en' || saved === 'de') return saved;
  const browser = (navigator.language || '').slice(0, 2).toLowerCase();
  return browser === 'en' ? 'en' : 'de';
}

function setLanguage(lang) {
  if (lang !== 'de' && lang !== 'en') lang = 'de';
  currentLang = lang;
  document.documentElement.lang = lang;
  localStorage.setItem('disrupt_lang', lang);

  // Update title & meta description
  if (I18N[lang]['meta.title']) document.title = I18N[lang]['meta.title'];
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && I18N[lang]['meta.desc']) metaDesc.content = I18N[lang]['meta.desc'];

  // Update all [data-i18n] elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (I18N[lang] && I18N[lang][key] !== undefined) {
      el.innerHTML = I18N[lang][key];
    }
  });

  // Update toggle buttons aria-pressed and active classes
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const active = btn.dataset.lang === lang;
    btn.setAttribute('aria-pressed', String(active));
    btn.classList.toggle('active', active);
  });

  // Dispatch custom event for dynamic components (app.js)
  window.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
}

function initI18n() {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const targetLang = btn.dataset.lang;
      if (targetLang && targetLang !== currentLang) {
        setLanguage(targetLang);
      }
    });
  });

  const initial = getInitialLang();
  if (initial !== 'de') {
    setLanguage(initial);
  } else {
    document.querySelectorAll('.lang-btn').forEach(btn => {
      const isDe = btn.dataset.lang === 'de';
      btn.setAttribute('aria-pressed', String(isDe));
      btn.classList.toggle('active', isDe);
    });
  }
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}

window.DISRUPT_I18N = {
  get current() { return currentLang; },
  set: setLanguage,
  dict: I18N
};
